"""Keep track of every ASSUMPTION we make and write reports/assumptions.md.

Assumptions are stored under "assumptions" in metrics.json (so the API can serve
them later) and the markdown report is rebuilt from that list every time.
"""

from engine import config
from engine.metrics import load_metrics, save_metrics_section

# The tariff is a config value, not computed — it is always part of the list.
TARIFF_ASSUMPTION = {
    "key": "tariff_inr_per_kwh",
    "title": "Electricity tariff used to convert lost kWh into ₹",
    "value": config.TARIFF_INR_PER_KWH,
    "unit": "₹/kWh",
    "why": ("Assumed value, configurable as TARIFF_INR_PER_KWH in engine/config.py (re-run the pipeline after "
            "changing it). Shown on the website as \"assumed tariff — see About\"."),
    "source": ("Rounded value between recent Indian solar tariffs: SECI 2 GW solar + 1 GW/4 GWh storage tender, "
               "lowest bid ₹2.86/kWh ([Power Peak Digest, 17 Oct 2025](https://powerpeakdigest.com/seci-auction-"
               "discovers-lowest-tariff-for-2-gw-solar-with-1-gw-4-gwh-storage/)) and SECI rooftop solar auction, "
               "₹3.34–4.65/kWh ([Indian Infrastructure, 17 Dec 2025](https://indianinfrastructure.com/2025/12/17/"
               "seci-announces-auction-results-for-6-25-mw-rooftop-solar-auction/))."),
}


def record_assumption(key, title, value, unit, why, source):
    """Add or update one assumption, then rewrite reports/assumptions.md."""
    stored = load_metrics().get("assumptions", [])
    entries = {item["key"]: item for item in stored}
    entries[TARIFF_ASSUMPTION["key"]] = TARIFF_ASSUMPTION
    entries[key] = {"key": key, "title": title, "value": value, "unit": unit,
                    "why": why, "source": source}
    assumption_list = list(entries.values())
    save_metrics_section("assumptions", assumption_list)
    _write_report(assumption_list)


def _write_report(assumption_list):
    """Write the list of assumptions as a beginner-friendly markdown table."""
    lines = ["# Assumptions", "",
             "_Generated by the pipeline — do not edit by hand._", "",
             "Anything we could not measure directly is listed here, with its value and why we chose it.",
             "In code these are marked `ASSUMPTION`; in the dashboard they get an ⓘ note.", "",
             "| Assumption | Value | Why / how it was chosen | Source |", "|---|---|---|---|"]
    for item in assumption_list:
        lines.append(f"| {item['title']} | {item['value']} {item['unit']} | {item['why']} | {item['source']} |")
    config.ASSUMPTIONS_REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
